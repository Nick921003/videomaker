#!/usr/bin/env python3
"""story 資料夾 → 影片專案：lib/story.js（併入 keys.json 的關鍵詞）、assets/audio/narration.wav、captions.srt。

用法：
  python3 video_engine/explainer/sync_film.py <story 資料夾> <影片專案>

分鏡的電腦畫面描述（screens.json 的 screen／do）也併進 story.js，連同共用元件、黑板轉接、主題檔一起放進 lib/。

黑板上只寫關鍵詞（story.json 每句的 key），完整字幕走 .srt 讓觀眾自己開關（冗餘原則，使用者 2026-10-26 選 B）。
輸出影片後把 captions.srt 複製成跟 mp4 同名，播放器會自動載入。
"""
import json
import os
import shutil
import sys

CUE_MAX = 22  # 一行字幕超過這麼多字就從逗號切成兩個 cue，時間照字數分


def merge_keys(story, keys):
	for L in story["lines"]:
		k = keys.get(str(L["i"]))
		if k:
			L["key"] = k
	return story


ENGINE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def merge_screens(story, screens):
	"""分鏡寫的電腦畫面描述（screens.json 的 screen／do）併進 story：改畫面不用重跑語音合成"""
	extra = {tuple(sc["lines"]): sc for sc in screens if sc.get("screen")}
	have = {tuple(sc["lines"]) for sc in story.get("screens", [])}
	lost = [list(k) for k in extra if k not in have]
	if lost:
		# 對不上就整段畫面不見（beats.js 也不再畫它），螢幕會是空的，不能安靜略過
		raise ValueError("screens.json 的電腦畫面句號對不上 story.json：%s（分鏡改過句號，story.json 也要跟著重新產生）" % lost)
	for sc in story.get("screens", []):
		hit = extra.get(tuple(sc["lines"]))
		if hit:
			sc["screen"], sc["do"] = hit["screen"], hit["do"]
	return story


def merge_objects(story, objects):
	"""分鏡的黑板元件頁（objects.json）併成 story.boards；句號對不上整頁就不見，不能安靜略過"""
	if not objects:
		return story
	have = {tuple(p) for p in story.get("pages", [])}
	lost = [b["lines"] for b in objects if tuple(b["lines"]) not in have]
	if lost:
		raise ValueError("objects.json 的黑板頁句號對不上 story.json：%s（分鏡改過句號，story.json 也要跟著重新產生）" % lost)
	story["boards"] = [{k: b[k] for k in ("lines", "template", "objects", "do", "dir") if k in b} for b in objects]
	return story


CHALK = os.path.join(ENGINE, "explainer", "chalk")
# 黑板的執行核心與 kit：tools/sync.sh 原本從 kits/<風格> 複製，那個目錄在這個 repo 不存在，改由這裡帶
CHALK_CORE = ("core.js", "sfxlib.py")
CHALK_KIT = ("kit.js", "kit.css", "chalk-mask.png", "grain.svg", "chalklog.mjs",
	"vscode.chalk.js", "icon.chalk.js", "note.chalk.js", "board_tpl.js", "board.chalk.js")


def copy_components(project):
	"""跨風格共用的元件核心、黑板核心與轉接、主題檔放進片子的 lib/（HyperFrames 只看得到專案目錄）"""
	dst = os.path.join(project, "lib", "components")
	if os.path.exists(dst):
		shutil.rmtree(dst)
	shutil.copytree(os.path.join(ENGINE, "components"), dst, ignore=shutil.ignore_patterns("*.py", "*.md", "__pycache__"))
	os.makedirs(os.path.join(project, "lib", "kit"), exist_ok=True)
	for name in CHALK_CORE:
		shutil.copy(os.path.join(CHALK, "core", name), os.path.join(project, "lib", name))
	for name in CHALK_KIT:
		shutil.copy(os.path.join(CHALK, "kit", name), os.path.join(project, "lib", "kit", name))
	with open(os.path.join(project, "lib", "themes.js"), "w", encoding="utf-8") as f:
		f.write("/* generated by sync_film.py from video_engine/themes — edit the themes, not this file */\n")
		for var, name in (("VSCODE_THEME", "vscode_dark.json"), ("TONES", "tones.json")):
			with open(os.path.join(ENGINE, "themes", name), encoding="utf-8") as src:
				f.write("window.%s = %s;\n" % (var, json.dumps(json.load(src), ensure_ascii=False)))


def _ts(t):
	ms = int(round(t * 1000))
	return "%02d:%02d:%02d,%03d" % (ms // 3600000, ms // 60000 % 60, ms // 1000 % 60, ms % 1000)


def _split(text):
	if len(text) <= CUE_MAX:
		return [text]
	cut = max((i for i, c in enumerate(text[:-1]) if c in "，：；" and i < len(text) - 4), default=-1, key=lambda i: -abs(i - len(text) / 2))
	return [text] if cut < 0 else [text[:cut + 1], text[cut + 1:]]


def srt(story):
	cues = []
	lines = list(story["lines"])
	say = (story.get("recap") or {}).get("say")
	if isinstance(say, dict):
		lines.append(say)
	for L in lines:
		parts = _split(L["text"])
		t, span = L["start"], L["end"] - L["start"]
		total = sum(len(p) for p in parts)
		for p in parts:
			d = span * len(p) / total
			cues.append((t, t + d, p))
			t += d
	return "".join("%d\n%s --> %s\n%s\n\n" % (n + 1, _ts(a), _ts(b), x) for n, (a, b, x) in enumerate(cues))


def main(story_dir, project):
	with open(os.path.join(story_dir, "story.json"), encoding="utf-8") as f:
		story = json.load(f)
	kp = os.path.join(story_dir, "keys.json")
	if os.path.exists(kp):
		with open(kp, encoding="utf-8") as f:
			merge_keys(story, json.load(f))
	sp = os.path.join(story_dir, "screens.json")
	if os.path.exists(sp):
		with open(sp, encoding="utf-8") as f:
			merge_screens(story, json.load(f))
	op = os.path.join(story_dir, "objects.json")
	if os.path.exists(op):
		with open(op, encoding="utf-8") as f:
			merge_objects(story, json.load(f))
	copy_components(project)
	with open(os.path.join(project, "lib/story.js"), "w", encoding="utf-8") as f:
		f.write("/* generated by sync_film.py from %s/story.json — edit the story, not this file */\nwindow.STORY = " % os.path.basename(os.path.abspath(story_dir)))
		json.dump(story, f, ensure_ascii=False)
		f.write(";\n")
	# starter 不附 assets/audio/（旁白是每支片自己的），從 starter 開的新片第一次同步要自己建
	os.makedirs(os.path.join(project, "assets/audio"), exist_ok=True)
	shutil.copy(os.path.join(story_dir, "audio/narration.wav"), os.path.join(project, "assets/audio/narration.wav"))
	with open(os.path.join(project, "captions.srt"), "w", encoding="utf-8") as f:
		f.write(srt(story))
	print("寫出 lib/story.js、lib/components、lib/themes.js、assets/audio/narration.wav、captions.srt")


if __name__ == "__main__":
	main(sys.argv[1], sys.argv[2])
